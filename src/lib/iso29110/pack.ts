export function findPackIssues(): string[] {
  const issues: string[] = [];
  const docs = ISO_DOC_TABS.flatMap((tab) => tab.docs);
  const codes = new Set(docs.map((doc) => doc.code));
  for (const code of [
    "WP-SOW",
    "WP-PLAN",
    "WP-REQ",
    "WP-DES",
    "WP-TRACE",
    "WP-TC",
    "WP-TR",
    "WP-OPS",
    "WP-USER",
    "WP-MAINT",
    "WP-VER",
    "WP-VAL",
    "WP-ACC",
    "WP-CFG",
    "WP-PROGRESS",
    "WP-MEET",
    "WP-CR",
    "WP-CORR",
  ]) {
    if (!codes.has(code)) issues.push(`ขาดเอกสาร ${code}`);
  }
  const trace = docs.find((doc) => doc.code === "WP-TRACE");
  const traceText = JSON.stringify(trace?.blocks ?? []);
  for (const req of REQ_IDS) {
    if (!traceText.includes(req)) issues.push(`${req} ไม่มีใน WP-TRACE`);
  }
  const tests = docs.find((doc) => doc.code === "WP-TC");
  const testText = JSON.stringify(tests?.blocks ?? []);
  for (const req of [
    "REQ-01",
    "REQ-02",
    "REQ-03",
    "REQ-04",
    "REQ-05",
    "REQ-06",
    "REQ-11",
    "REQ-12",
    "REQ-13",
    "REQ-14",
  ]) {
    if (!testText.includes(req)) issues.push(`${req} ไม่มีกรณีทดสอบ`);
  }
  const val = JSON.stringify(docs.find((doc) => doc.code === "WP-VAL")?.blocks ?? []);
  const acc = JSON.stringify(docs.find((doc) => doc.code === "WP-ACC")?.blocks ?? []);
  if (!val.includes("รอลงนาม") || !acc.includes("รอลงนาม")) {
    issues.push("ช่องลงนามถูกรีบปิดทั้งที่ยังไม่มีผู้มีอำนาจเซ็น");
  }
  const report = JSON.stringify(docs.find((doc) => doc.code === "WP-TR")?.blocks ?? []);
  if (
    report.includes("TC-11") &&
    report.includes("ผ่าน") &&
    report.includes("รอพื้นโรงงาน") === false
  ) {
    issues.push("TC หน้างานถูกบันทึกว่าผ่านทั้งที่ยังไม่รัน");
  }
  return issues;
}
